def get_wuxing_state(wuxing: str, month_dizhi: str) -> str:
    """获取五行在月令中的旺衰状态"""
    for state, dizhis in YUANLING_STATES[wuxing].items():
        if month_dizhi in dizhis:
            return state
    return "休"
