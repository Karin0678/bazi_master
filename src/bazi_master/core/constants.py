# 十神关系（以日干为我）
# 同我（同五行）：比肩（同阴阳）、劫财（异阴阳）
# 我生（我生之）：食神（同阴阳）、伤官（异阴阳）
# 我克（我克之）：正财（异阴阳）、偏财（同阴阳）
# 克我（克我之）：正官（异阴阳）、七杀（同阴阳）
# 生我（生我之）：正印（异阴阳）、偏印（同阴阳）

def get_shishen(day_gan: str, target_gan: str) -> str:
    """计算十神关系"""
    day_wx = TIANGAN_WUXING[day_gan]
    target_wx = TIANGAN_WUXING[target_gan]
    day_yy = TIANGAN_YINYANG[day_gan]
    target_yy = TIANGAN_YINYANG[target_gan]
    same_yy = (day_yy == target_yy)

    if day_wx == target_wx:
        return "比肩" if same_yy else "劫财"
    elif WUXING_SHENG[day_wx] == target_wx:
        return "食神" if same_yy else "伤官"
    elif WUXING_KE[day_wx] == target_wx:
        return "偏财" if same_yy else "正财"
    elif WUXING_KE[target_wx] == day_wx:
        return "七杀" if same_yy else "正官"
    elif WUXING_SHENG[target_wx] == day_wx:
        return "偏印" if same_yy else "正印"
    return ""

